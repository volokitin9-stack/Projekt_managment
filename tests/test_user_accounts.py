def test_viewer_can_view_but_not_edit_a_project(tmp_path):
    srv = make_server(tmp_path, SEED_DEMO_DATA="true").start()
    try:
        admin = admin_session(srv)
        created = create_manager(admin, srv, "Петров Пётр", "petrov")
        s, _ = manager_session(srv, "petrov", created["generated_password"])
        projects = s.get(srv.url + "/api/projects", timeout=10).json()
        assert len(projects) > 0, "demo seed data must be present for this check"
        p = projects[0]
        assert s.get(srv.url + f"/api/projects/{p['id']}", timeout=10).status_code == 200

        patch = s.patch(srv.url + f"/api/projects/{p['id']}", json={"changes": {"priority": "high"}, "version": p["version"]}, timeout=10)
        assert patch.status_code == 403
        stage = s.post(srv.url + f"/api/projects/{p['id']}/stage", json={"stage": "development"}, timeout=10)
        assert stage.status_code == 403
        comment = s.post(srv.url + f"/api/projects/{p['id']}/comments", json={"text": "test"}, timeout=10)
        assert comment.status_code == 403
        upload = s.post(srv.url + f"/api/projects/{p['id']}/files", files={"file": ("x.jpg", b"fake", "image/jpeg")}, timeout=10)
        assert upload.status_code == 403

        # the project must be completely untouched by every refused attempt
        after = s.get(srv.url + f"/api/projects/{p['id']}", timeout=10).json()
        assert after["version"] == p["version"] and after["priority"] == p["priority"]
    finally:
        srv.stop()


