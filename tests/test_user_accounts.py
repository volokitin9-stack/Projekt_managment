def test_viewer_cannot_download_the_raw_uploads_path_but_can_view_a_photo_inline(tmp_path):
    srv = make_server(tmp_path, SEED_DEMO_DATA="true").start()
    try:
        admin = admin_session(srv)
        projects = admin.get(srv.url + "/api/projects", timeout=10).json()
        pid = projects[0]["id"]
        up = admin.post(srv.url + f"/api/projects/{pid}/files",
                         files={"file": ("photo.jpg", b"\xff\xd8\xff\xe0fakejpeg", "image/jpeg")}, timeout=10)
        assert up.status_code == 201, up.text
        file_info = up.json()
        assert file_info["view_url"].startswith(f"/api/projects/{pid}/files/")

        created = create_manager(admin, srv, "Петров Пётр", "petrov")
        s, _ = manager_session(srv, "petrov", created["generated_password"])

        raw = s.get(srv.url + file_info["url"], timeout=10)
        assert raw.status_code == 403

        viewed = s.get(srv.url + file_info["view_url"], timeout=10)
        assert viewed.status_code == 200
        assert viewed.content == b"\xff\xd8\xff\xe0fakejpeg"
        assert "attachment" not in (viewed.headers.get("Content-Disposition") or "")

        # the administrator keeps using the raw path exactly as before
        assert admin.get(srv.url + file_info["url"], timeout=10).status_code == 200
    finally:
        srv.stop()


