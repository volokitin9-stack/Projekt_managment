"""Individual manager accounts ("Пользователи" admin section, role ko_viewer) - "Разграничение
доступа к «Доске проектов»". The administrator identity stays DASHBOARD_USERNAME/DASHBOARD_PASSWORD
(server/dashboardAuth.js), unchanged; this is the new, separate "users" collection
(server/usersModel.js) layered alongside it. No real credentials here - every password is
generated by the server itself or a throwaway test literal.
"""
import time

import pytest
import requests

from conftest import ShturmanServer

ADMIN_USER, ADMIN_PASS = "admin", "s3cret-admin!"


def make_server(tmp_path, **env):
    e = {"DASHBOARD_USERNAME": ADMIN_USER, "DASHBOARD_PASSWORD": ADMIN_PASS,
         "DASHBOARD_SESSION_SECRET": "test-session-secret"}
    e.update(env)
    return ShturmanServer(tmp_path / "srv", extra_env=e)


def admin_session(srv):
    s = requests.Session()
    r = s.post(srv.url + "/api/login", json={"username": ADMIN_USER, "password": ADMIN_PASS}, timeout=10)
    assert r.status_code == 200, r.text
    return s


def csrf_of(session, srv):
    return session.get(srv.url + "/api/whoami", timeout=10).json()["csrf_token"]


def create_manager(session, srv, full_name, username, password=None):
    body = {"full_name": full_name, "username": username}
    if password:
        body["password"] = password
    r = session.post(srv.url + "/api/users", json=body, headers={"X-CSRF-Token": csrf_of(session, srv)}, timeout=10)
    assert r.status_code == 201, r.text
    return r.json()


def manager_session(srv, username, password):
    s = requests.Session()
    r = s.post(srv.url + "/api/login", json={"username": username, "password": password}, timeout=10)
    return s, r


@pytest.fixture
def srv(tmp_path):
    s = make_server(tmp_path).start()
    yield s
    s.stop()


# ------------------------------------------------------------------ 1-2: create managers, independence

def test_admin_creates_several_independent_managers(srv):
    admin = admin_session(srv)
    a = create_manager(admin, srv, "Петров Пётр", "petrov")
    b = create_manager(admin, srv, "Сидоров Сидор", "sidorov")
    assert a["user"]["id"] != b["user"]["id"]
    assert a["user"]["role"] == "ko_viewer" and b["user"]["role"] == "ko_viewer"
    assert a["generated_password"] and b["generated_password"] and a["generated_password"] != b["generated_password"]

    s_a, r_a = manager_session(srv, "petrov", a["generated_password"])
    s_b, r_b = manager_session(srv, "sidorov", b["generated_password"])
    assert r_a.status_code == 200 and r_b.status_code == 200
    who_a = s_a.get(srv.url + "/api/whoami", timeout=10).json()
    who_b = s_b.get(srv.url + "/api/whoami", timeout=10).json()
    assert who_a["username"] == "petrov" and who_b["username"] == "sidorov"
    assert who_a["role"] == who_b["role"] == "ko_viewer"

    # disabling one must never affect the other
    uid_a = a["user"]["id"]
    admin.post(srv.url + f"/api/users/{uid_a}/disable", headers={"X-CSRF-Token": csrf_of(admin, srv)}, timeout=10)
    assert s_a.get(srv.url + "/api/projects", timeout=10).status_code == 401
    assert s_b.get(srv.url + "/api/projects", timeout=10).status_code == 200


