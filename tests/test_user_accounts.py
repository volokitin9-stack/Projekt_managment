# ------------------------------------------------------------------ 4: no access to another session

def test_a_managers_cookie_cannot_be_reused_to_act_as_another_user(srv):
    admin = admin_session(srv)
    a = create_manager(admin, srv, "Петров Пётр", "petrov")
    b = create_manager(admin, srv, "Сидоров Сидор", "sidorov")
    s_a, _ = manager_session(srv, "petrov", a["generated_password"])
    s_b, _ = manager_session(srv, "sidorov", b["generated_password"])
    # each session's cookie is independent - swapping cookies between two requests.Session
    # objects is the realistic model of "an attacker gets hold of someone else's cookie string"
    cookie_a = s_a.cookies.get("shturman_session")
    cookie_b = s_b.cookies.get("shturman_session")
    assert cookie_a and cookie_b and cookie_a != cookie_b
    who_with_a = requests.get(srv.url + "/api/whoami", cookies={"shturman_session": cookie_a}, timeout=10).json()
    who_with_b = requests.get(srv.url + "/api/whoami", cookies={"shturman_session": cookie_b}, timeout=10).json()
    assert who_with_a["username"] == "petrov" and who_with_b["username"] == "sidorov"

    # a tampered/invented cookie value must never authenticate as anyone
    forged = requests.get(srv.url + "/api/whoami", cookies={"shturman_session": cookie_a[:-2] + "xx"}, timeout=10)
    assert forged.json()["authenticated"] is False


# ------------------------------------------------------------------ 5: instant lockout of an active session

def test_disabling_a_user_instantly_kills_their_open_session(srv):
    admin = admin_session(srv)
    created = create_manager(admin, srv, "Петров Пётр", "petrov")
    uid = created["user"]["id"]
    s, _ = manager_session(srv, "petrov", created["generated_password"])
    assert s.get(srv.url + "/api/projects", timeout=10).status_code == 200

    r = admin.post(srv.url + f"/api/users/{uid}/disable", headers={"X-CSRF-Token": csrf_of(admin, srv)}, timeout=10)
    assert r.status_code == 200 and r.json()["active"] is False

    # the exact same, still-unexpired cookie - no new login, no logout - must be dead right now
    assert s.get(srv.url + "/api/projects", timeout=10).status_code == 401
    assert s.get(srv.url + "/api/whoami", timeout=10).json()["authenticated"] is False


# ------------------------------------------------------------------ 6: reactivation

def test_reactivation_requires_a_fresh_login_old_session_stays_dead(srv):
    admin = admin_session(srv)
    created = create_manager(admin, srv, "Петров Пётр", "petrov")
    uid = created["user"]["id"]
    s, _ = manager_session(srv, "petrov", created["generated_password"])
    csrf = csrf_of(admin, srv)
    admin.post(srv.url + f"/api/users/{uid}/disable", headers={"X-CSRF-Token": csrf}, timeout=10)
    r = admin.post(srv.url + f"/api/users/{uid}/activate", headers={"X-CSRF-Token": csrf}, timeout=10)
    assert r.status_code == 200 and r.json()["active"] is True

    # the pre-disable cookie must NOT silently come back to life just because the account did
    assert s.get(srv.url + "/api/projects", timeout=10).status_code == 401

    # a fresh login with the same (never-reset) password works again
    s2, r2 = manager_session(srv, "petrov", created["generated_password"])
    assert r2.status_code == 200
    assert s2.get(srv.url + "/api/projects", timeout=10).status_code == 200


# ------------------------------------------------------------------ 7: password reset

def test_password_reset_invalidates_old_password_and_old_sessions(srv):
    admin = admin_session(srv)
    created = create_manager(admin, srv, "Петров Пётр", "petrov")
    uid = created["user"]["id"]
    old_password = created["generated_password"]
    s_old, _ = manager_session(srv, "petrov", old_password)
    assert s_old.get(srv.url + "/api/projects", timeout=10).status_code == 200

    r = admin.post(srv.url + f"/api/users/{uid}/reset-password", headers={"X-CSRF-Token": csrf_of(admin, srv)}, timeout=10)
    assert r.status_code == 200
    new_password = r.json()["generated_password"]
    assert new_password and new_password != old_password

    # the live session from before the reset is dead immediately
    assert s_old.get(srv.url + "/api/projects", timeout=10).status_code == 401
    # the old password no longer works at all
    _, bad = manager_session(srv, "petrov", old_password)
    assert bad.status_code == 401
    # the new one does
    s_new, ok = manager_session(srv, "petrov", new_password)
    assert ok.status_code == 200
    assert s_new.get(srv.url + "/api/projects", timeout=10).status_code == 200


def test_login_rate_limiting_locks_out_after_repeated_failures(srv):
    admin = admin_session(srv)
    created = create_manager(admin, srv, "Петров Пётр", "petrov")
    for _ in range(5):
        _, r = manager_session(srv, "petrov", "wrong-password")
        assert r.status_code == 401
    _, locked = manager_session(srv, "petrov", "wrong-password")
    assert locked.status_code == 429
    # even the CORRECT password is refused while locked out
    _, still_locked = manager_session(srv, "petrov", created["generated_password"])
    assert still_locked.status_code == 429


